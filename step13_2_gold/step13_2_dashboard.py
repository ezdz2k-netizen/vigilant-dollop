"""Step 13.2 GOLD delayed entry/exit research dashboard. Read-only CSV viewer."""
from pathlib import Path
import pandas as pd
import streamlit as st
import plotly.express as px

st.set_page_config(page_title='GOLD Step 13.2 | Execution Research',layout='wide')
st.title('GOLD Step 13.2 — Delayed Entry & Trade Management')
st.caption('Research only · M1 OHLC modeled fills · No real MT5 orders')
with st.sidebar:
    path=Path(st.text_input('Results directory',str(Path(__file__).parent/'results')))
    st.caption('Results generated by step13_2_engine.py')

def read(name):
    f=path/name
    if not f.exists():return pd.DataFrame()
    try:return pd.read_csv(f)
    except pd.errors.EmptyDataError:return pd.DataFrame()

hold=read('holdout_comparison.csv');fold=read('walkforward_folds.csv');sel=read('development_selections.csv');trades=read('holdout_trades.csv')
if hold.empty:
    st.info('No backtest results yet. Run step13_2_engine.py first.');st.stop()
mode=st.selectbox('Higher timeframe',sorted(hold['mode'].unique()))
method=st.selectbox('Entry confirmation',sorted(hold.loc[hold['mode']==mode,'method'].unique()))
d=hold[(hold['mode']==mode)&(hold['method']==method)].copy()
st.subheader('Final holdout — descriptive comparison')
st.warning('The final holdout has been previously examined in earlier GOLD research. Do not select a new winning strategy from these results and call it independently validated.')
st.dataframe(d[['config','selected','trades','eligible_signals','return_pct','profit_factor','win_rate_pct','max_drawdown_pct','avg_r']],hide_index=True,use_container_width=True)
fig=px.bar(d,x='config',y='return_pct',color='selected',title='Holdout return by execution variation')
st.plotly_chart(fig,use_container_width=True)
a,b,c=st.columns(3)
base=d[d.config=='baseline'];pick=d[d.selected==True]
a.metric('Baseline return',f"{float(base.iloc[0].return_pct):.2f}%" if len(base) else '—')
b.metric('Development-selected',str(pick.iloc[0]['config']) if len(pick) else '—')
c.metric('Selected holdout return',f"{float(pick.iloc[0].return_pct):.2f}%" if len(pick) else '—')
st.subheader('Rolling development results')
f=fold[(fold['mode']==mode)&(fold['method']==method)]
if not f.empty:
    st.plotly_chart(px.bar(f,x='fold',y='return_pct',color='config',barmode='group',title='Walk-forward fold returns'),use_container_width=True)
    with st.expander('Full development fold details'):st.dataframe(f,use_container_width=True,hide_index=True)
st.subheader('Virtual trade audit')
t=trades[(trades['mode']==mode)&(trades['method']==method)] if not trades.empty else pd.DataFrame()
if len(t):
    chosen=st.selectbox('Trade variation',sorted(t['config'].unique()))
    tt=t[t['config']==chosen].copy()
    st.dataframe(tt,use_container_width=True,hide_index=True)
    st.download_button('Download selected trades',tt.to_csv(index=False),'step13_2_trades.csv','text/csv')
    if 'exit_reason' in tt:st.plotly_chart(px.histogram(tt,x='exit_reason',title='Exit reasons'),use_container_width=True)
else:st.info('No trades in this mode/method.')
with st.expander('Data quality and methodology'):
    report=path/'report.json'
    if report.exists():st.json(report.read_text())
    st.caption('M1 OHLC is not tick-perfect. A threshold touched inside an M1 bar is filled no earlier than the following available M1 open.')
